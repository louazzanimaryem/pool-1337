#include <unistd.h>

void	ft_putnbr(int nb)
{
	long int		n;
	long int		arr[20];
	char			c;
	int				i;

	n = nb;
	i = 0;
	if (n < 0)
	{
		write(1, "-", 1);
		n = -n;
	}
	if (n == 0)
		write(1, "0", 1);
	while (n > 0)
	{
		arr[i++] = n % 10;
		n /= 10;
	}
	i--;
	while (i >= 0)
	{
		c = arr[i--] + '0';
		write(1, &c, 1);
	}
}
